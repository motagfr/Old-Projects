from datetime import datetime


def time_dist(times: tuple):
    pt1 = datetime.strptime(times[0], '%H:%M:%S')
    seconds1 = pt1.second + pt1.minute*60 + pt1.hour*3600
    pt2 = datetime.strptime(times[1], '%H:%M:%S')
    seconds2 = pt2.second + pt2.minute*60 + pt2.hour*3600
    return seconds2-seconds1


